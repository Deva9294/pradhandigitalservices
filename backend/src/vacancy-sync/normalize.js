export function normalizeVacancyRecord(record = {}) {
  return {
    title: record.title || '',
    titleHindi: record.titleHindi || '',
    department: record.department || '',
    organization: record.organization || '',
    advertisementNumber: record.advertisementNumber || '',
    externalExamId: record.externalExamId || '',
    vacancyType: record.vacancyType || 'state',
    employmentType: record.employmentType || 'regular',
    totalPosts: Number(record.totalPosts || 0),
    qualification: record.qualification || '',
    qualificationTags: Array.isArray(record.qualificationTags) ? record.qualificationTags : [],
    ageMinimum: Number(record.ageMinimum || 0),
    ageMaximum: Number(record.ageMaximum || 0),
    ageRelaxation: record.ageRelaxation || '',
    applicationFee: record.applicationFee || '',
    state: record.state || 'Madhya Pradesh',
    district: record.district || '',
    category: record.category || 'government',
    startDate: record.startDate || null,
    lastDate: record.lastDate || null,
    correctionDate: record.correctionDate || null,
    examDate: record.examDate || null,
    notificationUrl: record.notificationUrl || '',
    applyUrl: record.applyUrl || '',
    officialWebsiteUrl: record.officialWebsiteUrl || '',
    sourceName: record.sourceName || 'Official Source',
    sourceDomain: record.sourceDomain || '',
    sourcePageUrl: record.sourcePageUrl || '',
    sourceKey: record.sourceKey || '',
    contentHash: record.contentHash || '',
    status: record.status || 'pending',
    verificationStatus: record.verificationStatus || 'pending_review',
    confidenceScore: Number(record.confidenceScore || 0.5),
    isFeatured: Boolean(record.isFeatured),
    isNew: Boolean(record.isNew),
    isUpdated: Boolean(record.isUpdated),
    firstSeenAt: record.firstSeenAt || new Date(),
    lastSeenAt: record.lastSeenAt || new Date(),
    lastCheckedAt: record.lastCheckedAt || new Date(),
    publishedAt: record.publishedAt || null,
    closedAt: record.closedAt || null,
    revisionHistory: Array.isArray(record.revisionHistory) ? record.revisionHistory : [],
    relatedUpdates: Array.isArray(record.relatedUpdates) ? record.relatedUpdates : [],
  };
}
